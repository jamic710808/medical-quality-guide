const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
process.env.TMPDIR = path.resolve('.codex/maintenance/tmp');
const { chromium } = require('playwright');
const out = path.resolve('.codex/maintenance');
const server = spawn('python3', ['-B', '-u', '-c', 'from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler\nfrom functools import partial\ns=ThreadingHTTPServer(("127.0.0.1",0),partial(SimpleHTTPRequestHandler,directory="docs/04_frontend-prototype"))\nprint(s.server_address[1],flush=True)\ns.serve_forever()'], {stdio:['ignore','pipe','pipe']});
const serverStopped = new Promise(resolve=>server.once('exit',resolve));
let serverLog='';server.stderr.on('data',d=>serverLog+=d);
let browser;
let page;
const checks=[];
const errors=[];
const ok = (name, actual, expected) => {assert.deepEqual(actual,expected,name);checks.push(name);console.log('PASS '+name);};
(async()=>{
  const port=await new Promise((resolve,reject)=>{server.stdout.once('data',d=>resolve(Number(d.toString().trim())));server.once('error',reject);});
  const base=`http://127.0.0.1:${port}`;
  console.log('Local server '+base);
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1280,height:800}});
  await context.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.abort());
  page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  const nav=async url=>{await page.goto(base+'/'+url);await page.locator('#main h1').waitFor();};
  const ids=()=>page.locator('.order-number').allTextContents();
  const role=()=>page.locator('#order-owner-filter').inputValue();
  const ui=()=>page.evaluate(()=>JSON.parse(sessionStorage.getItem('fulfillment-experience-20260928-v3-view')));
  const chooseRole=async value=>{await page.locator('#order-owner-filter').selectOption(value);};
  const goOrders=async()=>{await page.locator('#header nav a[href="index.html"]').click();await page.locator('#order-owner-filter').waitFor();};
  const reset=async()=>{await page.getByRole('button',{name:'重置演示',exact:true}).click();await page.getByRole('button',{name:'恢复初始数据',exact:true}).click();await page.waitForURL('**/index.html');await page.locator('#order-owner-filter').waitFor();};
  await nav('index.html');
  ok('初始18条及第1页8行',[(await page.locator('.pagination>span').first().innerText()),(await ids()).length],['1–8 / 共 18 条',8]);
  ok('新条件默认全部岗位',await role(),'全部岗位');
  await page.screenshot({path:path.join(out,'orders-1280.png')});
  for(const size of [{width:1280,height:800},{width:1440,height:900}]){
    await page.setViewportSize(size);
    const boxes=await page.locator('.order-workspace>.toolbar>label').evaluateAll(labels=>labels.map(label=>{const r=label.getBoundingClientRect();const p=label.parentElement.getBoundingClientRect();return {within:r.left>=p.left&&r.right<=p.right&&r.top>=p.top&&r.bottom<=p.bottom,visible:r.width>0&&r.height>0};}));
    ok(`${size.width}筛选控件完整位于工具栏内`,boxes.every(x=>x.within&&x.visible),true);
  }
  await page.screenshot({path:path.join(out,'orders-1440.png')});
  await page.setViewportSize({width:1280,height:800});
  await page.locator('#header nav a[href="followups.html"]').click();
  await page.locator('#role-filter').selectOption('采购');
  await page.locator('#task-search').fill('北辰');
  ok('既有协同岗位筛选可用',await page.locator('.queue-row-bottom small').allTextContents(),['采购负责']);
  const taskBefore=await ui();
  await goOrders();
  await chooseRole('交付');
  ok('订单岗位匹配10条交付订单',await page.locator('.pagination>span').first().innerText(),'1–8 / 共 10 条');
  ok('当前行岗位一致',new Set(await page.locator('.orders-table tbody td:nth-child(5)>strong').allTextContents()),new Set(['交付']));
  await page.locator('#order-search').fill('模块');
  await page.locator('[data-action="filter-order"][data-id="跟进中"]').click();
  await page.locator('#basis-filter').selectOption('到货');
  await page.locator('#order-sort').selectOption('customer');
  ok('岗位与搜索分类口径客户排序组合',await ids(),['SO-260928-041','SO-260928-065','SO-260928-026']);
  await page.locator('#order-sort').selectOption('due');
  ok('组合条件交付时间排序',await ids(),['SO-260928-026','SO-260928-041','SO-260928-065']);
  await page.locator('#order-sort').selectOption('customer');
  const combo=await ui();
  await page.locator('.order-number').first().click();
  await page.getByRole('link',{name:'返回订单列表',exact:true}).click();
  const returned=await ui();
  for(const key of ['query','group','basis','orderOwner','sort','orderPage'])ok('详情返回保留 '+key,returned[key],combo[key]);
  ok('详情返回匹配结果一致',await ids(),['SO-260928-041','SO-260928-065','SO-260928-026']);
  await page.reload();
  ok('刷新保留岗位',await role(),'交付');
  await page.locator('#header nav a[href="followups.html"]').click();
  const taskAfter=await ui();
  for(const key of ['role','task','taskQuery','taskPage','selectedTask'])ok('订单筛选不覆盖协同 '+key,taskAfter[key],taskBefore[key]);
  await page.locator('.task-order').click();
  await page.getByRole('link',{name:'返回协同队列',exact:true}).click();
  ok('既有协同详情返回保留岗位',await page.locator('#role-filter').inputValue(),'采购');
  await goOrders();
  await page.locator('#order-search').fill('不存在的订单');
  ok('组合条件空结果',await page.locator('.empty h3').innerText(),'没有匹配的订单');
  await page.getByRole('button',{name:'清除筛选',exact:true}).click();
  const cleared=await ui();
  ok('清除筛选恢复订单条件',[cleared.query,cleared.group,cleared.basis,cleared.orderOwner,cleared.orderPage,cleared.orderScroll],['','全部订单','全部口径','全部岗位',1,0]);
  ok('清除筛选继续保留排序',cleared.sort,'customer');
  ok('清除筛选不改协同条件',[cleared.role,cleared.taskQuery],['采购','北辰']);
  await chooseRole('交付');
  await page.locator('[data-action="order-page"][data-id="2"]').first().click();
  ok('岗位结果真实分页',await page.locator('.pagination>span').first().innerText(),'9–10 / 共 10 条');
  const second=await ids();
  await page.locator('.order-number').first().click();
  await page.getByRole('link',{name:'返回订单列表',exact:true}).click();
  ok('第2页返回保持结果',await ids(),second);
  ok('第2页返回保持岗位页码',[(await ui()).orderPage,await role()],[2,'交付']);
  await chooseRole('生产');
  ok('更换岗位回第1页并清零滚动',[(await ui()).orderPage,(await ui()).orderScroll,(await ids()).length],[1,0,6]);
  await chooseRole('交付');
  await page.locator('#order-scroll').hover();
  await page.mouse.wheel(0,600);
  await page.waitForFunction(()=>document.querySelector('#order-scroll').scrollTop>0);
  const scroll=await page.locator('#order-scroll').evaluate(el=>el.scrollTop);
  await page.locator('.order-number').last().click();
  await page.getByRole('link',{name:'返回订单列表',exact:true}).click();
  ok('岗位筛选详情返回保留表格位置',await page.locator('#order-scroll').evaluate(el=>el.scrollTop),scroll);
  await reset();
  const defaults=await ui();
  ok('重置演示恢复两页浏览默认值',[defaults.query,defaults.group,defaults.basis,defaults.orderOwner,defaults.sort,defaults.orderPage,defaults.orderScroll,defaults.role,defaults.task,defaults.taskQuery,defaults.taskPage,defaults.selectedTask],['','全部订单','全部口径','全部岗位','priority',1,0,'全部岗位','未完成','',1,'']);
  await chooseRole('计划');
  ok('原始北辰当前岗位为计划',await ids(),['SO-260928-018']);
  await page.locator('.order-number').click();
  await page.getByRole('link',{name:'方案比较',exact:true}).click();
  await page.getByRole('button',{name:'提交计划确认',exact:true}).click();
  await page.getByRole('link',{name:'办理调拨事项',exact:false}).click();
  await page.getByRole('button',{name:'确认方案并交仓储',exact:true}).click();
  await goOrders();
  ok('岗位变更后保留原筛选并显示空结果',[await role(),(await ids()).length],['计划',0]);
  ok('原岗位无当前订单仍可见',await page.locator('#order-owner-filter option:checked').innerText(),'计划');
  await chooseRole('仓储');
  ok('按当前仓储而非初始计划匹配',await ids(),['SO-260928-018']);
  await page.locator('.order-number').click();
  await page.getByRole('link',{name:'办理对应事项',exact:false}).click();
  await page.getByRole('button',{name:'接手办理',exact:true}).click();
  await page.getByRole('button',{name:'核对交接并记录结果',exact:true}).click();
  await goOrders();
  ok('交接后仓储筛选无结果',[(await ids()).length,await role()],[0,'仓储']);
  await chooseRole('生产');
  ok('交接后北辰进入生产岗位结果',(await ids()).includes('SO-260928-018'),true);
  await page.locator('.order-number',{hasText:'SO-260928-018'}).click();
  await page.getByRole('link',{name:'办理对应事项',exact:false}).click();
  await page.getByRole('button',{name:'接受生产安排',exact:true}).click();
  await goOrders();
  ok('组合岗位不误归单一生产',(await ids()).includes('SO-260928-018'),false);
  await chooseRole('生产 / 质量');
  ok('完整组合岗位可筛出北辰',await ids(),['SO-260928-018']);
  ok('筛选岗位与表格显示相同',await page.locator('.orders-table tbody td:nth-child(5)>strong').innerText(),'生产 / 质量');
  await page.screenshot({path:path.join(out,'current-owner-combined.png')});
  await reset();
  ok('重置恢复业务岗位及全部订单',[await role(),await page.locator('.pagination>span').first().innerText()],['全部岗位','1–8 / 共 18 条']);
  await chooseRole('计划');
  ok('重置后北辰恢复计划岗位',await ids(),['SO-260928-018']);
  await page.locator('#header nav a[href="followups.html"]').click();
  ok('从协同页也可重置',await page.locator('#role-filter').inputValue(),'全部岗位');
  await page.locator('#role-filter').selectOption('交付');
  await reset();
  ok('协同页发起重置也清空订单岗位',await role(),'全部岗位');
  ok('浏览器无脚本异常',errors,[]);
  fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify({status:'pass',port,checks,errors,viewports:['1280x800','1440x900'],browser:browser.version()},null,2));
  console.log(`PASS ${checks.length} assertions; browser ${browser.version()}`);
})().catch(async error=>{
  console.error(error.stack);
  if(page)await page.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});
  process.exitCode=1;
}).finally(async()=>{
  if(browser)await browser.close();
  server.kill('SIGTERM');
  await serverStopped;
  fs.writeFileSync(path.join(out,'server.log'),serverLog);
  console.log('Browser and local server stopped.');
});
